-- 1. CUSTOMER
CREATE TABLE CUSTOMER (
    CUSTOMER_ID       NUMBER         PRIMARY KEY,
    FIRST_NAME        VARCHAR2(50)   NOT NULL,
    LAST_NAME         VARCHAR2(50)   NOT NULL,
    PHONE             VARCHAR2(20),
    EMAIL             VARCHAR2(100),
    ADDRESS           VARCHAR2(255),
    REGISTRATION_DATE DATE           DEFAULT SYSDATE
);

-- 2. CATEGORY
CREATE TABLE CATEGORY (
    CATEGORY_ID   NUMBER        PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION   VARCHAR2(500)
);

-- 3. MENU_ITEM
CREATE TABLE MENU_ITEM (
    ITEM_ID      NUMBER        PRIMARY KEY,
    ITEM_NAME    VARCHAR2(150) NOT NULL,
    DESCRIPTION  VARCHAR2(500),
    CATEGORY_ID  NUMBER        REFERENCES CATEGORY(CATEGORY_ID),
    PRICE        NUMBER(10,2)  NOT NULL,
    AVAILABILITY VARCHAR2(10)  DEFAULT 'Yes' CHECK (AVAILABILITY IN ('Yes','No'))
);

-- 4. EMPLOYEE
CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID NUMBER        PRIMARY KEY,
    FIRST_NAME  VARCHAR2(50)  NOT NULL,
    LAST_NAME   VARCHAR2(50)  NOT NULL,
    PHONE       VARCHAR2(20),
    ROLE        VARCHAR2(50),
    SALARY      NUMBER(10,2),
    HIRE_DATE   DATE,
    STATUS      VARCHAR2(20)  DEFAULT 'Active' CHECK (STATUS IN ('Active','Inactive'))
);

-- 5. APP_USER  ("PASSWORD" is quoted — reserved word in Oracle)
CREATE TABLE APP_USER (
    USER_ID      NUMBER        PRIMARY KEY,
    USERNAME     VARCHAR2(50)  NOT NULL UNIQUE,
    "PASSWORD"   VARCHAR2(255) NOT NULL,
    EMPLOYEE_ID  NUMBER        REFERENCES EMPLOYEE(EMPLOYEE_ID),
    STATUS       VARCHAR2(20)  DEFAULT 'Active' CHECK (STATUS IN ('Active','Inactive')),
    CREATED_DATE DATE          DEFAULT SYSDATE
);

-- 6. ORDERS  (not ORDER — reserved word)
CREATE TABLE ORDERS (
    ORDER_ID     NUMBER       PRIMARY KEY,
    CUSTOMER_ID  NUMBER       REFERENCES CUSTOMER(CUSTOMER_ID),
    EMPLOYEE_ID  NUMBER       REFERENCES EMPLOYEE(EMPLOYEE_ID),
    ORDER_TYPE   VARCHAR2(30) CHECK (ORDER_TYPE IN ('Dine-In','Takeaway','Delivery')),
    ORDER_DATE   DATE         DEFAULT SYSDATE,
    STATUS       VARCHAR2(30) DEFAULT 'Pending',
    TOTAL_AMOUNT NUMBER(10,2) DEFAULT 0
);

-- 7. ORDER_ITEM
CREATE TABLE ORDER_ITEM (
    ORDER_ITEM_ID        NUMBER        PRIMARY KEY,
    ORDER_ID             NUMBER        REFERENCES ORDERS(ORDER_ID),
    ITEM_ID              NUMBER        REFERENCES MENU_ITEM(ITEM_ID),
    QUANTITY             NUMBER        NOT NULL,
    UNIT_PRICE           NUMBER(10,2)  NOT NULL,
    SUBTOTAL             NUMBER(10,2),
    SPECIAL_INSTRUCTIONS VARCHAR2(500)
);

-- 8. KITCHEN_ORDER
CREATE TABLE KITCHEN_ORDER (
    KITCHEN_ORDER_ID NUMBER        PRIMARY KEY,
    ORDER_ID         NUMBER        REFERENCES ORDERS(ORDER_ID),
    KITCHEN_STATUS   VARCHAR2(30)  DEFAULT 'Pending',
    STARTED_AT       DATE          DEFAULT SYSDATE,
    READY_AT         DATE,
    NOTES            VARCHAR2(500)
);

-- 9. PAYMENT
CREATE TABLE PAYMENT (
    PAYMENT_ID     NUMBER        PRIMARY KEY,
    ORDER_ID       NUMBER        REFERENCES ORDERS(ORDER_ID),
    AMOUNT         NUMBER(10,2)  NOT NULL,
    PAYMENT_STATUS VARCHAR2(20)  DEFAULT 'Paid' CHECK (PAYMENT_STATUS IN ('Paid','Unpaid','Refunded')),
    PAYMENT_DATE   DATE          DEFAULT SYSDATE
);

-- 10. INVENTORY_ITEM
CREATE TABLE INVENTORY_ITEM (
    INVENTORY_ID      NUMBER        PRIMARY KEY,
    ITEM_NAME         VARCHAR2(150) NOT NULL,
    UNIT              VARCHAR2(30),
    QUANTITY_IN_STOCK NUMBER(10,2)  DEFAULT 0,
    REORDER_LEVEL     NUMBER(10,2)  DEFAULT 0,
    UNIT_COST         NUMBER(10,2),
    LAST_UPDATED      DATE          DEFAULT SYSDATE
);

-- 11. SUPPLIER
CREATE TABLE SUPPLIER (
    SUPPLIER_ID   NUMBER        PRIMARY KEY,
    SUPPLIER_NAME VARCHAR2(150) NOT NULL,
    PHONE         VARCHAR2(20),
    EMAIL         VARCHAR2(100),
    ADDRESS       VARCHAR2(255),
    STATUS        VARCHAR2(20)  DEFAULT 'Active' CHECK (STATUS IN ('Active','Inactive'))
);

-- 12. SUPPLIER_INVENTORY
CREATE TABLE SUPPLIER_INVENTORY (
    SUPPLIER_ID      NUMBER       REFERENCES SUPPLIER(SUPPLIER_ID),
    INVENTORY_ID     NUMBER       REFERENCES INVENTORY_ITEM(INVENTORY_ID),
    SUPPLY_PRICE     NUMBER(10,2),
    LAST_SUPPLY_DATE DATE,
    CONSTRAINT PK_SUPPLIER_INVENTORY PRIMARY KEY (SUPPLIER_ID, INVENTORY_ID)
);

-- 13. SYS_SETTINGS
CREATE TABLE SYS_SETTINGS (
    SETTING_KEY   VARCHAR2(100) PRIMARY KEY,
    SETTING_VALUE VARCHAR2(500),
    UPDATED_BY    NUMBER,
    UPDATED_AT    DATE DEFAULT SYSDATE
);

-- 14. NOTIFICATIONS
CREATE TABLE NOTIFICATIONS (
    NOTIF_ID   NUMBER        PRIMARY KEY,
    USER_ID    NUMBER        REFERENCES APP_USER(USER_ID),
    TITLE      VARCHAR2(200) NOT NULL,
    MESSAGE    VARCHAR2(500),
    TYPE       VARCHAR2(30)  DEFAULT 'info',
    IS_READ    NUMBER(1)     DEFAULT 0,
    CREATED_AT DATE          DEFAULT SYSDATE,
    LINK_URL   VARCHAR2(300)
);

-- 15. USER_PREFERENCES (dark mode + language per account)
CREATE TABLE USER_PREFERENCES (
    USER_ID    NUMBER        PRIMARY KEY REFERENCES APP_USER(USER_ID),
    THEME      VARCHAR2(10)  DEFAULT 'light',
    LANGUAGE   VARCHAR2(10)  DEFAULT 'en',
    UPDATED_AT DATE          DEFAULT SYSDATE
);

